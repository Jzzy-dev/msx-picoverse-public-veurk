#!/usr/bin/env python3
# tables.inc for PICOAMP.COM: python3 gen_tables.py > tables.inc
#
# The picture area (oscilloscope, equalizer) is 24 x 10 cells = 192 x 80
# pixels, kept in RAM as 10 rows of 24 cells x 8 bytes (the order of the
# VDP's pattern table), so a pixel (x, y) is the byte
#   (y >> 3) * 192 + (x & F8h) + (y & 7),  bit 7 - (x & 7)
W, H = 192, 80
GREEN, YELLOW, RED, NAVY, BLUE_D = 8, 9, 11, 14, 2

print('; generated by gen_tables.py')
# scope: signed sample byte (the engine's sample / 256) -> y, 0 = top
ys = []
for b in range(256):
    v = b - 256 if b >= 128 else b
    y = 40 - (v * 5) // 8
    ys.append(max(0, min(H - 1, y)))
print('scope_y:')
for i in range(0, 256, 16):
    print('        db ' + ','.join('%d' % v for v in ys[i:i + 16]))
# y -> byte offset of its line in the first cell column
print('row_off:')
for i in range(0, H, 8):
    print('        dw ' + ','.join('%d' % ((y >> 3) * W + (y & 7)) for y in range(i, i + 8)))
# scope colours by line: green in the middle, yellow, red at the edges, a dim
# centre line
cols = []
for y in range(H):
    d = abs(y - 39.5)
    fg = GREEN if d < 22 else YELLOW if d < 33 else RED
    bg = BLUE_D if y == 40 else NAVY
    cols.append(fg * 16 + bg)
print('scope_col:')
for i in range(0, H, 16):
    print('        db ' + ','.join('#%02X' % v for v in cols[i:i + 16]))
